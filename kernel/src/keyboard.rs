//! Unified PS/2 and USB HID keyboard driver.
//!
//! PS/2 scancodes (set 1) arrive on IRQ1; USB boot-protocol reports are fed in
//! from the UHCI driver. Both paths share one modifier state, one key-event
//! queue, and one character queue. The shell and window manager consume key
//! events, while the legacy `read_char` API stays available to userland.

use core::sync::atomic::{AtomicBool, Ordering};

use crate::io::{inb, outb};
use crate::sync::SpinLock;
use crate::timer;

const DATA_PORT: u16 = 0x60;
const STATUS_PORT: u16 = 0x64;

const STATUS_OUTPUT_FULL: u8 = 0x01;
const STATUS_INPUT_FULL: u8 = 0x02;

const CMD_DISABLE_KEYBOARD: u8 = 0xAD;
const CMD_ENABLE_KEYBOARD: u8 = 0xAE;
const KBD_SET_LEDS: u8 = 0xED;

const QUEUE_CAPACITY: usize = 64;
const CHAR_CAPACITY: usize = 128;

const REPEAT_DELAY: u64 = 40; // 400 ms at 100 Hz
const REPEAT_INTERVAL: u64 = 4; // 40 ms at 100 Hz

/// A logical key independent of the device it came from.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Key {
    Char(u8),
    Enter,
    Backspace,
    Tab,
    Escape,
    Up,
    Down,
    Left,
    Right,
    Home,
    End,
    PageUp,
    PageDown,
    Insert,
    Delete,
    F(u8),
}

/// One key transition. `pressed` is false for releases; `repeat` marks a
/// repeat generated by the USB software autorepeat timer.
#[derive(Clone, Copy)]
pub struct KeyEvent {
    pub key: Key,
    pub pressed: bool,
    pub repeat: bool,
    pub shift: bool,
    pub ctrl: bool,
    pub alt: bool,
    pub caps: bool,
}

#[derive(Clone, Copy, Default)]
struct Modifiers {
    left_shift: bool,
    right_shift: bool,
    left_ctrl: bool,
    right_ctrl: bool,
    left_alt: bool,
    right_alt: bool,
    caps: bool,
    num: bool,
    scroll: bool,
}

impl Modifiers {
    fn shift(&self) -> bool {
        self.left_shift || self.right_shift
    }

    fn ctrl(&self) -> bool {
        self.left_ctrl || self.right_ctrl
    }

    fn alt(&self) -> bool {
        self.left_alt || self.right_alt
    }

    fn leds(&self) -> u8 {
        (self.scroll as u8) | ((self.num as u8) << 1) | ((self.caps as u8) << 2)
    }
}

struct EventBuffer {
    data: [KeyEvent; QUEUE_CAPACITY],
    head: usize,
    tail: usize,
}

const EMPTY_EVENT: KeyEvent = KeyEvent {
    key: Key::Char(0),
    pressed: false,
    repeat: false,
    shift: false,
    ctrl: false,
    alt: false,
    caps: false,
};

static EVENTS: SpinLock<EventBuffer> = SpinLock::new(EventBuffer {
    data: [EMPTY_EVENT; QUEUE_CAPACITY],
    head: 0,
    tail: 0,
});

struct CharBuffer {
    data: [u8; CHAR_CAPACITY],
    head: usize,
    tail: usize,
}

static CHARS: SpinLock<CharBuffer> = SpinLock::new(CharBuffer {
    data: [0; CHAR_CAPACITY],
    head: 0,
    tail: 0,
});

struct Input {
    modifiers: Modifiers,
    extended: bool,
    skip: u8,
    num_pad: bool,
    usb_keys: [u8; 6],
    usb_held: Option<(Key, u8)>, // logical key and HID usage
    usb_repeat_at: u64,
    usb_keyboard: bool,
    ps2_leds: u8,
    leds_pending: bool,
}

static INPUT: SpinLock<Input> = SpinLock::new(Input {
    modifiers: Modifiers {
        left_shift: false,
        right_shift: false,
        left_ctrl: false,
        right_ctrl: false,
        left_alt: false,
        right_alt: false,
        caps: false,
        num: false,
        scroll: false,
    },
    extended: false,
    skip: 0,
    num_pad: false,
    usb_keys: [0; 6],
    usb_held: None,
    usb_repeat_at: 0,
    usb_keyboard: false,
    ps2_leds: 0,
    leds_pending: false,
});

static INITIALIZED: AtomicBool = AtomicBool::new(false);

fn push_char(byte: u8) {
    let mut buffer = CHARS.lock();
    let next = (buffer.tail + 1) % buffer.data.len();
    if next == buffer.head {
        buffer.head = (buffer.head + 1) % buffer.data.len();
    }
    let tail = buffer.tail;
    buffer.data[tail] = byte;
    buffer.tail = next;
}

fn push_event(event: KeyEvent) {
    let mut buffer = EVENTS.lock();
    let next = (buffer.tail + 1) % buffer.data.len();
    if next == buffer.head {
        buffer.head = (buffer.head + 1) % buffer.data.len();
    }
    let tail = buffer.tail;
    buffer.data[tail] = event;
    buffer.tail = next;
}

fn char_of(key: Key) -> Option<u8> {
    match key {
        Key::Char(byte) => Some(byte),
        Key::Enter => Some(b'\n'),
        Key::Backspace => Some(0x08),
        Key::Tab => Some(b'\t'),
        Key::Escape => Some(0x1B),
        _ => None,
    }
}

fn emit(key: Key, pressed: bool, repeat: bool, modifiers: Modifiers) {
    let event = KeyEvent {
        key,
        pressed,
        repeat,
        shift: modifiers.shift(),
        ctrl: modifiers.ctrl(),
        alt: modifiers.alt(),
        caps: modifiers.caps,
    };
    push_event(event);
    if pressed {
        if let Some(byte) = char_of(key) {
            push_char(byte);
        }
    }
}

#[inline]
fn shifted(base: u8, shifted_value: u8, shift: bool, caps: bool, letter: bool) -> u8 {
    if shift ^ (caps && letter) {
        shifted_value
    } else {
        base
    }
}

/// Map a PS/2 set-1 make code (without the release bit) to a logical key.
fn scancode_key(code: u8, extended: bool, modifiers: Modifiers, num: bool) -> Option<Key> {
    if extended {
        return match code {
            0x1C => Some(Key::Enter),
            0x35 => Some(Key::Char(b'/')),
            0x47 => Some(Key::Home),
            0x48 => Some(Key::Up),
            0x49 => Some(Key::PageUp),
            0x4B => Some(Key::Left),
            0x4D => Some(Key::Right),
            0x4F => Some(Key::End),
            0x50 => Some(Key::Down),
            0x51 => Some(Key::PageDown),
            0x52 => Some(Key::Insert),
            0x53 => Some(Key::Delete),
            _ => None,
        };
    }

    let shift = modifiers.shift();
    let caps = modifiers.caps;
    let key = match code {
        0x01 => Key::Escape,
        0x02 => Key::Char(shifted(b'1', b'!', shift, caps, false)),
        0x03 => Key::Char(shifted(b'2', b'@', shift, caps, false)),
        0x04 => Key::Char(shifted(b'3', b'#', shift, caps, false)),
        0x05 => Key::Char(shifted(b'4', b'$', shift, caps, false)),
        0x06 => Key::Char(shifted(b'5', b'%', shift, caps, false)),
        0x07 => Key::Char(shifted(b'6', b'^', shift, caps, false)),
        0x08 => Key::Char(shifted(b'7', b'&', shift, caps, false)),
        0x09 => Key::Char(shifted(b'8', b'*', shift, caps, false)),
        0x0A => Key::Char(shifted(b'9', b'(', shift, caps, false)),
        0x0B => Key::Char(shifted(b'0', b')', shift, caps, false)),
        0x0C => Key::Char(shifted(b'-', b'_', shift, caps, false)),
        0x0D => Key::Char(shifted(b'=', b'+', shift, caps, false)),
        0x0E => Key::Backspace,
        0x0F => Key::Tab,
        0x10 => Key::Char(shifted(b'q', b'Q', shift, caps, true)),
        0x11 => Key::Char(shifted(b'w', b'W', shift, caps, true)),
        0x12 => Key::Char(shifted(b'e', b'E', shift, caps, true)),
        0x13 => Key::Char(shifted(b'r', b'R', shift, caps, true)),
        0x14 => Key::Char(shifted(b't', b'T', shift, caps, true)),
        0x15 => Key::Char(shifted(b'y', b'Y', shift, caps, true)),
        0x16 => Key::Char(shifted(b'u', b'U', shift, caps, true)),
        0x17 => Key::Char(shifted(b'i', b'I', shift, caps, true)),
        0x18 => Key::Char(shifted(b'o', b'O', shift, caps, true)),
        0x19 => Key::Char(shifted(b'p', b'P', shift, caps, true)),
        0x1A => Key::Char(shifted(b'[', b'{', shift, caps, false)),
        0x1B => Key::Char(shifted(b']', b'}', shift, caps, false)),
        0x1C => Key::Enter,
        0x1E => Key::Char(shifted(b'a', b'A', shift, caps, true)),
        0x1F => Key::Char(shifted(b's', b'S', shift, caps, true)),
        0x20 => Key::Char(shifted(b'd', b'D', shift, caps, true)),
        0x21 => Key::Char(shifted(b'f', b'F', shift, caps, true)),
        0x22 => Key::Char(shifted(b'g', b'G', shift, caps, true)),
        0x23 => Key::Char(shifted(b'h', b'H', shift, caps, true)),
        0x24 => Key::Char(shifted(b'j', b'J', shift, caps, true)),
        0x25 => Key::Char(shifted(b'k', b'K', shift, caps, true)),
        0x26 => Key::Char(shifted(b'l', b'L', shift, caps, true)),
        0x27 => Key::Char(shifted(b';', b':', shift, caps, false)),
        0x28 => Key::Char(shifted(b'\'', b'"', shift, caps, false)),
        0x29 => Key::Char(shifted(b'`', b'~', shift, caps, false)),
        0x2B => Key::Char(shifted(b'\\', b'|', shift, caps, false)),
        0x2C => Key::Char(shifted(b'z', b'Z', shift, caps, true)),
        0x2D => Key::Char(shifted(b'x', b'X', shift, caps, true)),
        0x2E => Key::Char(shifted(b'c', b'C', shift, caps, true)),
        0x2F => Key::Char(shifted(b'v', b'V', shift, caps, true)),
        0x30 => Key::Char(shifted(b'b', b'B', shift, caps, true)),
        0x31 => Key::Char(shifted(b'n', b'N', shift, caps, true)),
        0x32 => Key::Char(shifted(b'm', b'M', shift, caps, true)),
        0x33 => Key::Char(shifted(b',', b'<', shift, caps, false)),
        0x34 => Key::Char(shifted(b'.', b'>', shift, caps, false)),
        0x35 => Key::Char(shifted(b'/', b'?', shift, caps, false)),
        0x37 => Key::Char(b'*'),
        0x39 => Key::Char(b' '),
        0x3B => Key::F(1),
        0x3C => Key::F(2),
        0x3D => Key::F(3),
        0x3E => Key::F(4),
        0x3F => Key::F(5),
        0x40 => Key::F(6),
        0x41 => Key::F(7),
        0x42 => Key::F(8),
        0x43 => Key::F(9),
        0x44 => Key::F(10),
        0x47 => {
            if num {
                Key::Char(b'7')
            } else {
                Key::Home
            }
        }
        0x48 => {
            if num {
                Key::Char(b'8')
            } else {
                Key::Up
            }
        }
        0x49 => {
            if num {
                Key::Char(b'9')
            } else {
                Key::PageUp
            }
        }
        0x4A => Key::Char(b'-'),
        0x4B => {
            if num {
                Key::Char(b'4')
            } else {
                Key::Left
            }
        }
        0x4C => {
            if num {
                Key::Char(b'5')
            } else {
                Key::Char(0)
            }
        }
        0x4D => {
            if num {
                Key::Char(b'6')
            } else {
                Key::Right
            }
        }
        0x4E => Key::Char(b'+'),
        0x4F => {
            if num {
                Key::Char(b'1')
            } else {
                Key::End
            }
        }
        0x50 => {
            if num {
                Key::Char(b'2')
            } else {
                Key::Down
            }
        }
        0x51 => {
            if num {
                Key::Char(b'3')
            } else {
                Key::PageDown
            }
        }
        0x52 => {
            if num {
                Key::Char(b'0')
            } else {
                Key::Insert
            }
        }
        0x53 => {
            if num {
                Key::Char(b'.')
            } else {
                Key::Delete
            }
        }
        0x57 => Key::F(11),
        0x58 => Key::F(12),
        _ => return None,
    };
    Some(key)
}

fn handle_scancode(code: u8) {
    let mut input = INPUT.lock();

    if code == 0xE0 {
        input.extended = true;
        return;
    }
    if code == 0xE1 {
        // Pause sends a long fixed sequence; ignore its remaining bytes.
        input.skip = 5;
        input.extended = false;
        return;
    }
    if input.skip > 0 {
        input.skip -= 1;
        return;
    }

    let released = code & 0x80 != 0;
    let code = code & 0x7F;
    let extended = input.extended;
    input.extended = false;

    // Track modifier keys first; they do not generate key events of their own.
    match (extended, code) {
        (false, 0x2A) => {
            input.modifiers.left_shift = !released;
            return;
        }
        (false, 0x36) => {
            input.modifiers.right_shift = !released;
            return;
        }
        (false, 0x1D) => {
            input.modifiers.left_ctrl = !released;
            return;
        }
        (true, 0x1D) => {
            input.modifiers.right_ctrl = !released;
            return;
        }
        (false, 0x38) => {
            input.modifiers.left_alt = !released;
            return;
        }
        (true, 0x38) => {
            input.modifiers.right_alt = !released;
            return;
        }
        (_, 0x3A) if !released => {
            input.modifiers.caps = !input.modifiers.caps;
            input.leds_pending = true;
            return;
        }
        (false, 0x45) if !released => {
            input.modifiers.num = !input.modifiers.num;
            input.num_pad = input.modifiers.num;
            input.leds_pending = true;
            return;
        }
        (false, 0x46) if !released => {
            input.modifiers.scroll = !input.modifiers.scroll;
            input.leds_pending = true;
            return;
        }
        _ => {}
    }

    let Some(key) = scancode_key(code, extended, input.modifiers, input.num_pad) else {
        return;
    };
    if key == Key::Char(0) {
        return;
    }

    let modifiers = input.modifiers;
    drop(input);
    emit(key, !released, false, modifiers);
}

/// IRQ1 handler: read the scancode and feed the shared state machine.
pub fn irq() {
    let code = unsafe { inb(DATA_PORT) };
    handle_scancode(code);
}

/// Feed a scancode that arrived through a shared controller read.
pub fn inject(code: u8) {
    handle_scancode(code);
}

/// Translate one HID keyboard usage to a logical key.
fn usb_usage_key(usage: u8, modifiers: Modifiers) -> Option<Key> {
    let shift = modifiers.shift();
    let caps = modifiers.caps;
    let key = match usage {
        0x04..=0x1D => {
            let letter = b'a' + (usage - 0x04);
            Key::Char(shifted(letter, letter - 32, shift, caps, true))
        }
        0x1E..=0x26 => {
            let digit = b'1' + (usage - 0x1E);
            let symbol = match digit {
                b'1' => b'!',
                b'2' => b'@',
                b'3' => b'#',
                b'4' => b'$',
                b'5' => b'%',
                b'6' => b'^',
                b'7' => b'&',
                b'8' => b'*',
                b'9' => b'(',
                _ => b')',
            };
            Key::Char(shifted(digit, symbol, shift, caps, false))
        }
        0x27 => Key::Char(shifted(b'0', b')', shift, caps, false)),
        0x28 => Key::Enter,
        0x29 => Key::Escape,
        0x2A => Key::Backspace,
        0x2B => Key::Tab,
        0x2C => Key::Char(b' '),
        0x2D => Key::Char(shifted(b'-', b'_', shift, caps, false)),
        0x2E => Key::Char(shifted(b'=', b'+', shift, caps, false)),
        0x2F => Key::Char(shifted(b'[', b'{', shift, caps, false)),
        0x30 => Key::Char(shifted(b']', b'}', shift, caps, false)),
        0x31 => Key::Char(shifted(b'\\', b'|', shift, caps, false)),
        0x32 => Key::Char(shifted(b'#', b'~', shift, caps, false)),
        0x33 => Key::Char(shifted(b';', b':', shift, caps, false)),
        0x34 => Key::Char(shifted(b'\'', b'"', shift, caps, false)),
        0x35 => Key::Char(shifted(b'`', b'~', shift, caps, false)),
        0x36 => Key::Char(shifted(b',', b'<', shift, caps, false)),
        0x37 => Key::Char(shifted(b'.', b'>', shift, caps, false)),
        0x38 => Key::Char(shifted(b'/', b'?', shift, caps, false)),
        0x3A => Key::F(1),
        0x3B => Key::F(2),
        0x3C => Key::F(3),
        0x3D => Key::F(4),
        0x3E => Key::F(5),
        0x3F => Key::F(6),
        0x40 => Key::F(7),
        0x41 => Key::F(8),
        0x42 => Key::F(9),
        0x43 => Key::F(10),
        0x44 => Key::F(11),
        0x45 => Key::F(12),
        0x49 => Key::Insert,
        0x4A => Key::Home,
        0x4B => Key::PageUp,
        0x4C => Key::Delete,
        0x4D => Key::End,
        0x4E => Key::PageDown,
        0x4F => Key::Right,
        0x50 => Key::Left,
        0x51 => Key::Down,
        0x52 => Key::Up,
        0x54 => Key::Char(b'/'),
        0x55 => Key::Char(b'*'),
        0x56 => Key::Char(b'-'),
        0x57 => Key::Char(b'+'),
        0x58 => Key::Enter,
        0x59..=0x61 => Key::Char(b'1' + (usage - 0x59)),
        0x62 => Key::Char(b'0'),
        0x63 => Key::Char(b'.'),
        _ => return None,
    };
    Some(key)
}

fn usb_modifiers(byte: u8) -> Modifiers {
    Modifiers {
        left_shift: byte & 0x02 != 0,
        right_shift: byte & 0x20 != 0,
        left_ctrl: byte & 0x01 != 0,
        right_ctrl: byte & 0x10 != 0,
        left_alt: byte & 0x04 != 0,
        right_alt: byte & 0x40 != 0,
        ..Modifiers::default()
    }
}

/// Feed a HID boot-keyboard report (`modifiers`, reserved, six usages).
pub fn usb_report(report: &[u8], length: usize) {
    crate::interrupt::without_interrupts(|| usb_report_inner(report, length));
}

fn usb_report_inner(report: &[u8], length: usize) {
    if length < 8 || report.len() < 8 {
        return;
    }
    let mut input = INPUT.lock();
    input.usb_keyboard = true;
    INITIALIZED.store(true, Ordering::Release);

    let mut modifiers = usb_modifiers(report[0]);
    modifiers.caps = input.modifiers.caps;
    modifiers.num = input.modifiers.num;
    modifiers.scroll = input.modifiers.scroll;
    input.modifiers = modifiers;

    // Lock keys are edge-triggered from the usage array, then removed so they
    // do not generate character events.
    let mut keys = [0u8; 6];
    for &usage in report[2..8].iter() {
        if usage == 0x39 {
            if !input.usb_keys.contains(&0x39) {
                input.modifiers.caps = !input.modifiers.caps;
                input.leds_pending = true;
            }
            continue;
        }
        if usage == 0x53 {
            if !input.usb_keys.contains(&0x53) {
                input.modifiers.num = !input.modifiers.num;
                input.leds_pending = true;
            }
            continue;
        }
        if usage == 0x47 {
            if !input.usb_keys.contains(&0x47) {
                input.modifiers.scroll = !input.modifiers.scroll;
                input.leds_pending = true;
            }
            continue;
        }
        if usage != 0 && !keys.contains(&usage) {
            if let Some(slot) = keys.iter().position(|value| *value == 0) {
                keys[slot] = usage;
            }
        }
    }

    let previous = input.usb_keys;
    let modifiers = input.modifiers;
    let mut held: Option<(Key, u8)> = None;
    for &usage in keys.iter() {
        if usage == 0 {
            continue;
        }
        if !previous.contains(&usage) {
            if let Some(key) = usb_usage_key(usage, modifiers) {
                emit(key, true, false, modifiers);
            }
        }
        if held.is_none() {
            if let Some(key) = usb_usage_key(usage, modifiers) {
                if char_of(key).is_some() || matches!(key, Key::Up | Key::Down | Key::Left | Key::Right | Key::Home | Key::End | Key::PageUp | Key::PageDown | Key::Delete | Key::Insert) {
                    held = Some((key, usage));
                }
            }
        }
    }

    if let Some((key, usage)) = held {
        if input.usb_held.map(|(_, held_usage)| held_usage) != Some(usage) {
            input.usb_held = Some((key, usage));
            input.usb_repeat_at = timer::ticks().saturating_add(REPEAT_DELAY);
        }
    } else {
        input.usb_held = None;
    }

    input.usb_keys = keys;
}

/// Periodic work: USB software autorepeat and PS/2 lock LEDs.
pub fn poll() {
    crate::interrupt::without_interrupts(poll_inner);
}

fn poll_inner() {
    let mut input = INPUT.lock();
    if let Some((key, _)) = input.usb_held {
        let now = timer::ticks();
        if now >= input.usb_repeat_at {
            input.usb_repeat_at = now.saturating_add(REPEAT_INTERVAL);
            let modifiers = input.modifiers;
            drop(input);
            emit(key, true, true, modifiers);
            input = INPUT.lock();
        }
    }

    let desired = input.modifiers.leds();
    let send = input.leds_pending || desired != input.ps2_leds;
    if send {
        input.leds_pending = false;
        input.ps2_leds = desired;
        drop(input);
        send_ps2_leds(desired);
        return;
    }
}

fn wait_input() -> bool {
    for _ in 0..100_000 {
        if unsafe { inb(STATUS_PORT) } & STATUS_INPUT_FULL == 0 {
            return true;
        }
    }
    false
}

fn wait_output() -> Option<u8> {
    for _ in 0..100_000 {
        let status = unsafe { inb(STATUS_PORT) };
        if status & STATUS_OUTPUT_FULL != 0 {
            return Some(unsafe { inb(DATA_PORT) });
        }
    }
    None
}

fn drain_ack() -> bool {
    for _ in 0..8 {
        match wait_output() {
            Some(0xFA) => return true,
            Some(0xFE) => return false,
            Some(_) => continue,
            None => return false,
        }
    }
    false
}

/// Program the PS/2 keyboard LED byte (bit 0 scroll, bit 1 num, bit 2 caps).
/// The keyboard is briefly disabled so the command bytes cannot interleave
/// with ordinary keystrokes.
fn send_ps2_leds(mask: u8) {
    crate::interrupt::without_interrupts(|| {
        if unsafe { inb(STATUS_PORT) } == 0xFF {
            return;
        }
        if !wait_input() {
            return;
        }
        unsafe { outb(STATUS_PORT, CMD_DISABLE_KEYBOARD) };
        if wait_input() {
            unsafe { outb(DATA_PORT, KBD_SET_LEDS) };
        }
        if drain_ack() && wait_input() {
            unsafe { outb(DATA_PORT, mask) };
            let _ = drain_ack();
        }
        if wait_input() {
            unsafe { outb(STATUS_PORT, CMD_ENABLE_KEYBOARD) };
        }
    });
}

/// Return the next key event, if any.
pub fn take_event() -> Option<KeyEvent> {
    crate::interrupt::without_interrupts(|| {
        let mut buffer = EVENTS.lock();
        if buffer.head == buffer.tail {
            return None;
        }
        let event = buffer.data[buffer.head];
        buffer.head = (buffer.head + 1) % buffer.data.len();
        Some(event)
    })
}

/// Return the next buffered character for the legacy syscall interface.
pub fn read_char() -> Option<u8> {
    crate::interrupt::without_interrupts(|| {
        let mut buffer = CHARS.lock();
        if buffer.head == buffer.tail {
            return None;
        }
        let value = buffer.data[buffer.head];
        buffer.head = (buffer.head + 1) % buffer.data.len();
        Some(value)
    })
}

/// Discard queued events and characters (used after modal dialogs).
pub fn flush() {
    crate::interrupt::without_interrupts(|| {
        let mut events = EVENTS.lock();
        events.head = events.tail;
        let mut chars = CHARS.lock();
        chars.head = chars.tail;
    });
}

/// Current lock-LED mask, for documentation and the system monitor.
pub fn led_mask() -> u8 {
    crate::interrupt::without_interrupts(|| INPUT.lock().modifiers.leds())
}

/// Whether a USB keyboard has delivered at least one report.
pub fn usb_present() -> bool {
    crate::interrupt::without_interrupts(|| INPUT.lock().usb_keyboard)
}

/// Mark a USB HID keyboard as enumerated, before its first report arrives.
pub fn usb_ready() {
    crate::interrupt::without_interrupts(|| {
        INPUT.lock().usb_keyboard = true;
    });
}

/// Whether the keyboard subsystem has been initialised.
pub fn present() -> bool {
    INITIALIZED.load(Ordering::Acquire)
}

/// Human-readable keyboard source for the Settings and Monitor windows.
pub fn source() -> &'static str {
    if usb_present() {
        "PS/2 + USB HID"
    } else {
        "PS/2 scancode set 1"
    }
}

/// Mark the keyboard subsystem ready. PS/2 is always assumed available.
pub fn init() {
    INITIALIZED.store(true, Ordering::Release);
}
